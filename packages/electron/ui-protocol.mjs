import { readFile, realpath, stat } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

function jsonForScript(value) {
  return JSON.stringify(value).replaceAll('<', '\\u003c').replaceAll('\u2028', '\\u2028').replaceAll('\u2029', '\\u2029');
}

export function injectUiRuntimeConfig(html, apiOrigin) {
  const script = `<script>(()=>{const a=${jsonForScript(apiOrigin)};if(window.__NOTNATIVE_API_BASE_URL__===undefined)window.__NOTNATIVE_API_BASE_URL__=a;if(window.__NOTNATIVE_LOCAL_ORIGIN__===undefined)window.__NOTNATIVE_LOCAL_ORIGIN__=a})()</script>`;
  const head = /<head(?:\s[^>]*)?>/iu.exec(html);
  if (head) return `${html.slice(0, head.index + head[0].length)}${script}${html.slice(head.index + head[0].length)}`;
  const close = /<\/head\s*>/iu.exec(html);
  if (close) return `${html.slice(0, close.index)}${script}${html.slice(close.index)}`;
  return `${script}${html}`;
}

export function resolveUiAssetPath(webDistDir, urlPath) {
  let decoded;
  try { decoded = decodeURIComponent(urlPath); } catch { return path.join(webDistDir, 'index.html'); }
  if (decoded.includes('\0')) return path.join(webDistDir, 'index.html');
  if (decoded.split(/[\\/]+/u).includes('..')) return path.join(webDistDir, 'index.html');
  const normalized = path.normalize(decoded).replace(/^([/\\])+/, '');
  const candidate = path.resolve(webDistDir, normalized || 'index.html');
  const relative = path.relative(path.resolve(webDistDir), candidate);
  if (relative.startsWith('..') || path.isAbsolute(relative)) return path.join(webDistDir, 'index.html');
  return candidate;
}

export function createUiProtocolHandler({ webDistDir, apiOrigin, fetchFile, fileStat = stat, fileRealPath = realpath, read = readFile }) {
  const rootPath = path.resolve(webDistDir);
  const indexPath = path.join(rootPath, 'index.html');
  return async (request) => {
    const url = new URL(request.url);
    if (url.protocol !== 'notnative-ui:' || url.host !== 'app' || url.username || url.password)
      return new Response('Not found', { status: 404 });
    if (request.method !== 'GET' && request.method !== 'HEAD') return new Response('Method not allowed', { status: 405 });
    // The manifest is generated by the local web server (and may include
    // query customizations), while the packaged UI is served from web-dist.
    // Forward this one well-known resource so the absolute HTML link works
    // under the custom app origin as well as HTTP browser origins.
    if (url.pathname === '/manifest.webmanifest') {
      const manifestUrl = new URL('/manifest.webmanifest', apiOrigin);
      manifestUrl.search = url.search;
      try {
        const response = await fetchFile(manifestUrl.href, { method: request.method });
        const headers = new Headers(response.headers);
        headers.set('x-content-type-options', 'nosniff');
        if (!headers.has('cache-control')) headers.set('cache-control', 'no-cache');
        return new Response(request.method === 'HEAD' ? null : response.body, {
          status: response.status, statusText: response.statusText, headers,
        });
      } catch {
        return new Response('NotNativeDesktop manifest is unavailable', { status: 503 });
      }
    }
    let assetPath = resolveUiAssetPath(rootPath, url.pathname);
    let metadata;
    try { metadata = await fileStat(assetPath); } catch { metadata = null; }
    if (!metadata?.isFile?.()) {
      // Only extensionless paths are client-side routes. Falling back for a
      // missing JS/CSS file returns HTML with status 200, which masks a broken
      // packaged build and prevents the renderer from booting.
      if (path.extname(url.pathname) !== '') return new Response('Not found', { status: 404 });
      assetPath = indexPath;
      try { metadata = await fileStat(assetPath); } catch { return new Response('NotNativeDesktop UI is unavailable', { status: 503 }); }
    }
    let realAssetPath;
    let realRootPath;
    try {
      [realAssetPath, realRootPath] = await Promise.all([fileRealPath(assetPath), fileRealPath(rootPath)]);
    }
    catch { return new Response('NotNativeDesktop UI is unavailable', { status: 503 }); }
    const relative = path.relative(realRootPath, realAssetPath);
    if (relative === '..' || relative.startsWith(`..${path.sep}`) || path.isAbsolute(relative))
      return new Response('Not found', { status: 404 });
    assetPath = realAssetPath;
    try {
      if (!(await fileStat(assetPath)).isFile()) return new Response('Not found', { status: 404 });
    } catch {
      return new Response('Not found', { status: 404 });
    }
    if (path.extname(assetPath).toLowerCase() === '.html') {
      try {
        const html = await read(assetPath, 'utf8');
        const body = request.method === 'HEAD' ? null : injectUiRuntimeConfig(String(html), apiOrigin);
        return new Response(body, { headers: {
          'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-store', 'x-content-type-options': 'nosniff',
        } });
      } catch { return new Response('NotNativeDesktop UI is unavailable', { status: 503 }); }
    }
    const response = await fetchFile(pathToFileURL(assetPath).href, { method: request.method });
    const headers = new Headers(response.headers);
    headers.set('x-content-type-options', 'nosniff');
    if (!headers.has('cache-control')) headers.set('cache-control', 'no-cache');
    return new Response(request.method === 'HEAD' ? null : response.body, {
      status: response.status, statusText: response.statusText, headers,
    });
  };
}
